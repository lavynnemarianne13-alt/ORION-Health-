"""
modules/visualize_space_frames.py
===============================================================================
Visual inspection of the space frames (ISS / microgravity) with the
pseudo-labels generated for the space dataset (Orion Project).

Goal
----
Load a few frames extracted from the astronaut videos
(`modules/extract_frames.py`) and draw on top:
  * the athlete's bounding-box;
  * the skeleton (connections between joints);
  * the numbered keypoints.

It serves to check whether the pseudo-labels (generated by
`modules/train_space_pose.py` from the COCO model) are coherent before
using them in the incremental training.

Usage
-----
    # 8 random samples from the train split
    python modules/visualize_space_frames.py --n 8 --cols 4

    # Inspect the validation split
    python modules/visualize_space_frames.py --split valid --n 6

    # Choose frames by name (without extension)
    python modules/visualize_space_frames.py --names WhatsApp_Video_2026-11-15_at_02_14_42_f000010

    # Open in an interactive window (requires a display)
    python modules/visualize_space_frames.py --show
"""

from __future__ import annotations

import argparse
import os
import random
from pathlib import Path

import cv2
import numpy as np
import matplotlib

matplotlib.use("Agg")  # headless; switch to "TkAgg" for an interactive window
import matplotlib.pyplot as plt

# Reuse the skeleton/keypoint definitions and the existing drawing routines,
# avoiding duplicating the index convention.
try:
    from visualize_keypoints import parse_label, denormalize, draw_annotations
except ModuleNotFoundError:  # executed as a module (`from modules.X import`)
    from modules.visualize_keypoints import parse_label, denormalize, draw_annotations

# --------------------------------------------------------------------------- #
# Paths
# --------------------------------------------------------------------------- #
PROJECT_ROOT = Path(__file__).resolve().parents[1]      # .../fitness_pose
# Root of the space dataset (can be overridden by an environment variable).
SPACE_ROOT = Path(os.environ.get(
    "ORION_SPACE_ROOT", "/home/rehlovestowrite/Orion_dataset/space_dataset"))

DEFAULT_OUT = PROJECT_ROOT / "outputs" / "space_frames_grid.png"


# --------------------------------------------------------------------------- #
# Sample selection
# --------------------------------------------------------------------------- #
def collect_samples(split: str, n: int, seed: int | None,
                    names: list[str] | None) -> tuple[list[Path], Path]:
    """Select images from the split and return (list, labels_folder)."""
    images_dir = SPACE_ROOT / split / "images"
    labels_dir = SPACE_ROOT / split / "labels"

    if names:
        return [images_dir / f"{nm}.jpg" for nm in names], labels_dir

    all_imgs = sorted(images_dir.glob("*.jpg"))
    if seed is not None:
        random.seed(seed)
    return random.sample(all_imgs, min(n, len(all_imgs))), labels_dir


# --------------------------------------------------------------------------- #
# Sample grid
# --------------------------------------------------------------------------- #
def plot_grid(image_paths: list[Path], labels_dir: Path,
              cols: int = 4, out_path: Path | None = None) -> None:
    if not image_paths:
        print("[warning] no image found to visualize.")
        return

    rows = int(np.ceil(len(image_paths) / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(5 * cols, 5 * rows))
    axes = np.atleast_2d(axes)

    for idx, img_path in enumerate(image_paths):
        ax = axes[idx // cols, idx % cols]
        img = cv2.imread(str(img_path))
        if img is None:
            ax.set_title(f"[failed to read] {img_path.name}", fontsize=8)
            ax.axis("off")
            continue

        label_path = labels_dir / f"{img_path.stem}.txt"
        if label_path.exists():
            bbox, kps_xy, kps_v = parse_label(label_path)
            h, w = img.shape[:2]
            kps_px = denormalize(kps_xy, w, h)
            annotated = draw_annotations(img, bbox, kps_px, kps_v)
            ax.imshow(cv2.cvtColor(annotated, cv2.COLOR_BGR2RGB))
        else:
            # Frame without pseudo-label (no teacher detection).
            ax.imshow(cv2.cvtColor(img, cv2.COLOR_BGR2RGB))
        ax.set_title(img_path.stem[:32], fontsize=8)
        ax.axis("off")

    # Hide empty axes of the grid.
    for idx in range(len(image_paths), rows * cols):
        axes[idx // cols, idx % cols].axis("off")

    fig.suptitle("Visual inspection: space frames (ISS) + pseudo-labels",
                 fontsize=12, y=0.995)
    fig.tight_layout()

    if out_path is not None:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(out_path, dpi=130, bbox_inches="tight")
        print(f"[ok] grid saved at: {out_path}")
    plt.close(fig)


def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Visualize the space frames and their pseudo-labels."
    )
    p.add_argument("--split", choices=["train", "valid"], default="train",
                   help="Split of the space dataset (default: train)")
    p.add_argument("--n", type=int, default=8, help="number of random images")
    p.add_argument("--seed", type=int, default=42, help="sampling seed")
    p.add_argument("--cols", type=int, default=4, help="columns in the grid")
    p.add_argument("--names", nargs="*", default=None,
                   help="specific frame names (without extension)")
    p.add_argument("--out", type=str, default=str(DEFAULT_OUT),
                   help="output PNG file")
    p.add_argument("--show", action="store_true",
                   help="opens an interactive window (requires a display)")
    return p.parse_args()


if __name__ == "__main__":
    args = _parse_args()

    samples, labels_dir = collect_samples(args.split, args.n, args.seed, args.names)
    print(f"[info] split={args.split} | {len(samples)} images | labels: {labels_dir}")

    if args.show:
        matplotlib.use("TkAgg", force=True)
        import matplotlib.pyplot as plt  # noqa: F811

    out = None if args.show else Path(args.out)
    plot_grid(samples, labels_dir, cols=args.cols, out_path=out)

    if args.show:
        plt.show()
